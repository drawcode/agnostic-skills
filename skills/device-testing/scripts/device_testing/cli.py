"""Front: resolve which device, load add-ons, run the command on that device's backend."""
import json
import sys

from . import commands, config, inputserver
from .backends import BACKENDS, Unsupported

EXIT_UNSUPPORTED = 3


def discover_all():
    found = {}
    for backend in BACKENDS:
        for serial, model in backend.discover().items():
            found[serial] = (backend, model)
    return found


def resolve(requested):
    aliases = config.aliases()
    if requested:
        serial = aliases.get(requested.lower(), requested)
        # Cheapest platform first, so an Android command never waits on iOS discovery.
        for backend in BACKENDS:
            if serial in backend.discover():
                return backend(serial)
        raise commands.Fail(f"'{requested}' is not attached -- known aliases: {' '.join(sorted(aliases))}")
    phones = discover_all()
    if not phones:
        raise commands.Fail("no device attached")
    if len(phones) == 1:
        serial, (backend, _) = next(iter(phones.items()))
        return backend(serial)
    default = aliases.get((config.get("DEVICE_DEFAULT") or "").lower())
    if default in phones:
        return phones[default][0](default)
    raise commands.Fail(f"{len(phones)} devices attached -- pass --device "
                        f"<{'|'.join(sorted(aliases)) or 'serial'}>, or set DEVICE_DEFAULT")


def devices():
    by_serial = {serial: alias for alias, serial in config.aliases().items()}
    default = (config.get("DEVICE_DEFAULT") or "").lower()
    print(json.dumps({"ok": True, "devices": [
        {"platform": backend.name, "serial": serial, "model": model, "alias": by_serial.get(serial),
         "default": by_serial.get(serial) == default}
        for serial, (backend, model) in discover_all().items()]}))
    return 0


def usage_markdown():
    """The command reference as markdown, so a skill's references/commands.md is generated from the
    tool and never drifts from it: `device help --markdown > references/commands.md`."""
    name = config.get("DEVICE_TESTING_NAME", "device")
    print(f"# `{name}` commands\n")
    print(f"Generated by `{name} help --markdown`; regenerate after adding a command.\n")
    print(f"`{name} [--device ALIAS|SERIAL|UDID] <command> [args]`. Same commands on every platform; the "
          "attached device decides the backend.\n")
    print("Exit codes: 0 ok, 1 failed, 2 a wait or check came back negative, 3 not supported on this platform.\n")
    print("| Command | Arguments | What it does |\n|---|---|---|")
    rows = [("devices", "", "attached devices: platform, serial, model, alias")]
    for cmd, (_, text) in sorted(commands.COMMANDS.items()):
        # Usage strings are "ARGS  description"; one without two spaces is a description alone.
        args, _, desc = text.partition("  ") if "  " in text else ("", "", text)
        rows.append((cmd, args.strip(), desc.strip()))
    for cmd, args, desc in rows:
        print(f"| `{cmd}` | {'`' + args.replace('|', chr(92) + '|') + '`' if args else ''} | {desc.replace('|', chr(92) + '|')} |")
    return 0


def usage():
    name = config.get("DEVICE_TESTING_NAME", "device")
    print(f"{name} [--device ALIAS|SERIAL|UDID] <command> [args]\n")
    print("Same commands on every platform; the attached device decides the backend.")
    print("Exit codes: 0 ok, 1 failed, 2 a wait or check came back negative, 3 not supported here.\n")
    print(f"  {'devices':<14} attached devices: platform, serial, model, alias")
    for name, (_, text) in sorted(commands.COMMANDS.items()):
        print(f"  {name:<14} {text}")
    return 0


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    requested = None
    while args and args[0] in ("--device", "-d"):
        if len(args) < 2:
            print("--device needs an alias, serial or UDID", file=sys.stderr)
            return 1
        requested, args = args[1], args[2:]
    try:
        commands.load_addons()
    except Exception as e:  # a broken add-on must not take the base down with it
        print(f"add-on failed to load: {e}", file=sys.stderr)
    if not args or args[0] in ("help", "-h", "--help"):
        return usage_markdown() if "--markdown" in args else usage()
    name, rest = args[0], args[1:]
    if name == "devices":
        return devices()
    try:
        device = resolve(requested)
        print(f"device: {device.name} {device.serial}", file=sys.stderr)
        return commands.dispatch(commands.Context(device), name, rest)
    except Unsupported as e:
        print(f"'{e}' is not supported on {device.name} yet", file=sys.stderr)
        return EXIT_UNSUPPORTED
    except commands.Fail as e:
        print(f"{config.get('DEVICE_TESTING_NAME', 'device')}: {e}", file=sys.stderr)
        return e.code
    except inputserver.ServerError as e:
        print(str(e), file=sys.stderr)
        return 1
    except Exception as e:  # a device tool failed; report it the same way on every platform
        print(f"{config.get('DEVICE_TESTING_NAME', 'device')}: {e}", file=sys.stderr)
        return 1
